import numpy as np


def RK4(func, t0, tf, y0, h):
    T = np.arange(t0, tf + h, h)
    Y = [np.array(y0, dtype=float)]

    for i in range(len(T) - 1):
        t = T[i]
        y = Y[-1]

        k1 = func(t, y)
        k2 = func(t + h / 2, y + h * k1 / 2)
        k3 = func(t + h / 2, y + h * k2 / 2)
        k4 = func(t + h, y + h * k3)

        y_new = y + h * (k1 + 2 * k2 + 2 * k3 + k4) / 6

        Y.append(y_new)

    return T, np.array(Y)


def f(t, y):
    return np.array([y[1], -y[0]])


